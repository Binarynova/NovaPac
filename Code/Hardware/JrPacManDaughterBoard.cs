    public JrPacManDaughterBoard(byte[] rawMainCpu)
    {
        _rawMainCpu = rawMainCpu;
        MergedProms = new byte[0x0120];
        DecryptedMemory = new byte[0x10000]; // 64KB for Jr. Pac-Man
    }
    
    public void Initialize(byte[] prom9e, byte[] prom9f, byte[] prom9p)
    {
        // 1. Merge the Colors (Your existing logic)
        for (int i = 0; i < 32; i++)
        {
            MergedProms[i] = (byte)((prom9f[i] << 4) | (prom9e[i] & 0x0F));
        }
        Array.Copy(prom9p, 0, MergedProms, 0x20, 256);

        // 2. Decrypt the CPU ROM
        Array.Copy(_rawMainCpu, DecryptedMemory, _rawMainCpu.Length);
        
        int address = 0;
        foreach (var entry in DecryptTable)
        {
            for (int i = 0; i < entry.count; i++)
            {
                if (address < DecryptedMemory.Length)
                {
                    DecryptedMemory[address] ^= (byte)entry.value;
                }
                address++;
            }
        }
    }
}